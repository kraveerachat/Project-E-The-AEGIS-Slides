test('V3 order, timing, final identity and assessment classifications match the brief', async ({ page }) => {
  expect(scenes).toHaveLength(18)
  expect(totalSeconds).toBe(875)
  expect(scenes.findIndex(s=>s.id==='hardware-setup')).toBe(scenes.findIndex(s=>s.id==='network')+1)
  expect(scenes.filter(s=>s.id.endsWith('-demo')).map(s=>s.seconds)).toEqual([90,90])
  await page.addInitScript(() => localStorage.setItem('aegis-presentation-language','en'))
  await page.emulateMedia({reducedMotion:'reduce'})
  await page.goto('/#cover')
  await expect(page.locator('h1')).toHaveText('Local Data Center, Monitoring, Network Infrastructure and Security Assessment')
  await page.goto('/#security-findings')
  await expect(page.locator('.assessment-status')).toHaveText(['PASS','OBSERVED','POTENTIAL','NOT TESTED','LIMITATION'])
  await expect(page.locator('main')).toContainText('74 PASS · 0 FAIL · 1 NOT TESTED / 75')
  await page.getByRole('button',{name:'Review evidence captures'}).click()
  await expect(page.locator('.assessment-dialog')).toBeVisible()
  await page.keyboard.press('ArrowRight')
  await expect(page.locator('main')).toHaveAttribute('data-scene-id','security-findings')
  await expect(page.locator('.assessment-dialog .missing-asset')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.locator('.assessment-dialog')).not.toBeVisible()
})

