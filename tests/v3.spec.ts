test('neutral test video expands, isolates navigation and restores the scene after exit/end', async ({ page }) => {
  // A neutral color clip exercises browser decoding. It is never a public AEGIS asset.
  await page.addInitScript(() => localStorage.setItem('aegis-presentation-language','en'))
  await page.emulateMedia({reducedMotion:'reduce'})
  await page.route('**/src/data/assets.ts',async route=> {
    const response = await route.fetch()
    await route.fulfill({response,body:(await response.text()).replaceAll(/status: ["']MISSING["']/g,'status: "AVAILABLE"')})
  })
  await page.route('**/assets/videos/idea1/idea1-demo.mp4',route=>route.fulfill({contentType:'video/mp4',body:readFileSync('tests/fixtures/playback.mp4')}))
  await page.goto('/#drive-demo')
  const video = page.locator('video')
  await expect(video).toBeVisible()
  await video.evaluate((element:HTMLVideoElement)=>element.play())
  await expect(page.locator('.media-focus')).toBeVisible()
  await expect(page.locator('.masthead')).toHaveAttribute('inert','')
  await video.evaluate((element:HTMLVideoElement)=>element.pause())
  await page.keyboard.press('Tab')
  await expect.poll(()=>page.evaluate(()=>document.activeElement?.tagName)).toBe('VIDEO')
  await page.keyboard.press('Tab')
  await expect.poll(()=>page.evaluate(()=>document.activeElement?.tagName)).toBe('VIDEO')
  await page.keyboard.press('ArrowRight')
  await expect(page.locator('main')).toHaveAttribute('data-scene-id','drive-demo')
  // Chromium's native media controls consume some keys inside their closed
  // shadow tree. Escape is handled when an application control has focus.
  await page.getByRole('button',{name:'Exit presentation video mode'}).focus()
  await page.keyboard.press('Escape')
  await expect(page.locator('.media-focus')).toHaveCount(0)
  await expect(page.getByRole('button',{name:'Enter presentation video mode'})).toBeFocused()
  expect(await video.evaluate((element:HTMLVideoElement)=>element.paused)).toBe(true)
  await video.evaluate((element:HTMLVideoElement)=>{ element.currentTime = 0; return element.play() })
  await expect(page.locator('.media-focus')).toBeVisible()
  await expect(page.locator('.media-focus')).toHaveCount(0,{timeout:10000})
  await expect(page.locator('main')).toHaveAttribute('data-scene-id','drive-demo')
  await page.emulateMedia({media:'print'})
  await expect(page.locator('video')).not.toBeVisible()
  await expect(page.locator('.video-static-frame .missing-asset')).toBeVisible()
  await page.emulateMedia({media:'screen'})
  await video.evaluate((element:HTMLVideoElement)=>{element.currentTime=0;return element.play()})
  await expect(page.locator('.media-focus')).toBeVisible()
  await page.locator('video source').dispatchEvent('error')
  await expect(page.locator('.media-focus')).toHaveCount(0)
  await expect(page.locator('.video-frame')).toBeFocused()
  await expect(page.locator('.video-frame .placeholder-state')).toHaveText('Media unavailable · replace the supplied file')
  await expect(page.locator('.masthead')).not.toHaveAttribute('inert','')
})

test('Thai scene text fits the recording canvas and narrow hardware inspection works', async ({ page }) => {
  await page.emulateMedia({reducedMotion:'reduce'})
  for (const scene of scenes) {
    await page.goto(`/#${scene.id}`)
    const out = await page.locator('main').evaluate(element=> {
      const footer = document.querySelector('.presentation-footer')!.getBoundingClientRect()
      return [...element.querySelectorAll('h1,h2,h3,p,table,figure,.evidence-panel,.architecture-features')].filter(child=> {
        if (child.closest('dialog') || child.closest('.scene-cover')) return false
        const r=child.getBoundingClientRect()
        return r.width>0 && r.height>0 && (r.bottom>footer.top+3 || r.left<0 || r.right>1920)
      }).map(child=>({text:child.textContent?.slice(0,65),class:child.className,bottom:child.getBoundingClientRect().bottom}))
    })
    expect(out,scene.id).toEqual([])
  }
  await page.setViewportSize({width:390,height:844})
  await page.goto('/#hardware-setup')
  await page.getByRole('button',{name:'ตรวจดู การติดตั้งอุปกรณ์'}).click()
  await expect(page.locator('.photo-dialog[open]')).toBeVisible()
  await page.getByRole('button',{name:'ปิดการตรวจดูภาพ'}).click()
})

